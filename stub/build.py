#!/usr/bin/env python3
"""Assemble stub/xmodem.s for each bit rate into src/kimtape/stub.py.

Each rate is assembled at two code origins and two data origins; the bytes
that move with each are the high bytes of its relocations.  --check fails if
the committed module differs from what the source assembles to.
"""

import argparse
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "xmodem.s")
OUTPUT = os.path.join(HERE, os.pardir, "src", "kimtape", "stub.py")
CLOCK = 1_000_000
RATES = (9600, 19200, 38400)
CODE_ORG, DATA_ORG = 0x1000, 0x8000
CONFIG = """\
MEMORY { RAM: start = %S, size = $1000, file = %O; }
SEGMENTS { CODE: load = RAM, type = rw; }
"""


def assemble(cycles, org, data, work):
    """Return (image, labels) for one build."""
    obj, out, lbl = (os.path.join(work, n) for n in ("s.o", "s.bin", "s.lbl"))
    cfg = os.path.join(work, "s.cfg")
    with open(cfg, "w", encoding="ascii") as handle:
        handle.write(CONFIG)
    subprocess.run(
        ["ca65", "-g", "-D", "CYC=%d" % cycles, "-D", "DATA=%d" % data]
        + ["-o", obj, SOURCE],
        check=True,
    )
    subprocess.run(
        ["ld65", "-C", cfg, "-S", str(org), "-Ln", lbl, "-o", out, obj], check=True
    )
    with open(out, "rb") as handle:
        image = handle.read()
    labels = {}
    with open(lbl, encoding="ascii") as handle:
        for line in handle:
            _, value, name = line.split()
            labels[name.lstrip(".")] = int(value, 16)
    return image, labels


def moved(base, other):
    """Offsets whose byte differs between two builds."""
    assert len(base) == len(other)
    return tuple(i for i, (a, b) in enumerate(zip(base, other)) if a != b)


def build(cycles, work):
    """Everything kimtape needs to know about one rate's stub."""
    image, labels = assemble(cycles, CODE_ORG, DATA_ORG, work)
    code = moved(image, assemble(cycles, CODE_ORG + 0x1000, DATA_ORG, work)[0])
    data = moved(image, assemble(cycles, CODE_ORG, DATA_ORG + 0x1000, work)[0])
    return {
        "cycles": cycles,
        "code": image,
        "code_relocs": code,
        "data_relocs": data,
        "entry": labels["entry"] - CODE_ORG,
        "critical": (labels["crit"] - CODE_ORG, labels["critend"] - CODE_ORG),
        "data_size": labels["DATASIZE"],
        "zero_page": (labels["ZP"], labels["NZP"]),
    }


def render(stubs):
    """The generated module's text."""
    out = [
        '"""XMODEM-CRC receive stubs for the KIM-1, one per bit rate.\n',
        "Generated by stub/build.py from stub/xmodem.s; do not edit.",
        '"""',
        "",
        "CLOCK = %d" % CLOCK,
        "CODE_ORG = 0x%04X" % CODE_ORG,
        "DATA_ORG = 0x%04X" % DATA_ORG,
        "STUBS = {",
    ]
    for rate, stub in stubs.items():
        out.append("    %d: {" % rate)
        for key, value in stub.items():
            if isinstance(value, bytes):
                hexed = value.hex()
                out.append('        "%s": bytes.fromhex(' % key)
                out.extend(
                    '            "%s"' % hexed[i : i + 64]
                    for i in range(0, len(hexed), 64)
                )
                out.append("        ),")
            else:
                out.append('        "%s": %r,' % (key, value))
        out.append("    },")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    """Build, then write or check the generated module."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if out of date")
    args = ap.parse_args()
    with tempfile.TemporaryDirectory() as work:
        text = render({rate: build(round(CLOCK / rate), work) for rate in RATES})
    if args.check:
        with open(OUTPUT, encoding="ascii") as handle:
            if handle.read() != text:
                sys.exit("stub.py is out of date; run stub/build.py")
        return
    with open(OUTPUT, "w", encoding="ascii") as handle:
        handle.write(text)


if __name__ == "__main__":
    main()
